#!/usr/bin/env python3
"""Scaffold a new vertical's blocklist ledger from the hardened Highways pattern.

    python blocklist_ledger/new_vertical.py --vertical raillive --name "Rail Live"

Emits `blocklist_ledger/<vertical>/` containing 01_schema.sql, 02_functions.sql,
03_verify.sql and README.md — the same four-file shape as `evcharge/` and
`highways/`, ready to apply in filename order.

WHY A GENERATOR. Adding a vertical is ~500 lines of SQL that is byte-identical to
the last one except for a prefix. Hand-cloning it is how a constraint name gets
missed (they share the schema-wide relation namespace, so an unprefixed one
collides), or how the sentinel guard silently doesn't make it across. The parts
that must not drift are baked in here instead.

WHAT IT DELIBERATELY DOES *NOT* EMIT

  04_ping.sql — obsolete on the Pro plan. `ledger_ping()` existed solely to reset
  the free tier's 7-day inactivity pause. Pro projects do not pause, so a new
  vertical needs no keepalive entry. The existing function keeps working; it is
  simply no longer load-bearing.

THREE THINGS THIS BAKES IN, EACH ONE PAID FOR ALREADY

  1. Prefixed table AND constraint names. A UNIQUE constraint creates an index,
     and index names share the schema-wide relation namespace — an unprefixed
     constraint name collides with the Labs/EVCharge/Highways ones.

  2. The dot guard, unconditionally. Highways learned this the expensive way: a
     column that can contain the literal 'UNKNOWN' normalizes to the perfectly
     well-formed key 'unknown', so the first unresolved company claims it and
     every later one is told is_new=false — silently dropped from the funnel.
     That is a wrong-answer bug, not a wasted-credit one. Labs and EVCharge
     predate the guard and remain exposed; every new vertical gets it, because a
     real domain always has a dot and no sentinel does. There is no flag to turn
     it off — omitting it has never once been the right call.

  3. Reused normalizers, never redefined. `normalize_domain`/`normalize_linkedin`
     are defined once in the Labs `02_functions.sql`. Copying them per vertical
     is how two verticals drift into normalizing the same domain differently, so
     the generated file references them and fails loudly if they are absent.

Argument names in the generated RPCs are identical to every other vertical's on
purpose: PostgREST matches JSON body keys to argument names, so a new vertical's
caller differs from its Labs twin by the URL alone. Do not "improve" them.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Identifier budget: Postgres truncates at 63 chars and the longest thing we
# generate is "<slug>_company_ledger_key_shaped" (slug + 32). Cap well short of
# the cliff so a silent truncation can never make two constraint names collide.
MAX_SLUG = 24
SLUG_RE = re.compile(r"^[a-z][a-z0-9_]*$")

# Verticals whose SQL already exists and is live. Regenerating one would overwrite
# hand-made, paid-for decisions (the Highways sentinel guard, the EVCharge
# "starting empty" note), so they are refused by name rather than by file check.
PROTECTED = {"labs", "evcharge", "highways"}


# --------------------------------------------------------------------------
# Templates. Placeholder tokens rather than f-strings/%-formatting: the SQL is
# full of $$ and % and {} that would otherwise all need escaping.
# --------------------------------------------------------------------------

SCHEMA_SQL = r"""
-- ============================================================================
-- @@NAME@@ blocklist / "have I seen this before?" ledger
-- @@SLUG@@/01_schema.sql  --  tables, constraints, lockdown
--
-- Run FIRST, in the SAME Supabase project as the Labs ledger. Idempotent.
--
-- Same pattern as blocklist_ledger/evcharge/ and blocklist_ledger/highways/:
-- prefixed tables and prefixed RPCs beside the Labs ones, never a discriminator
-- column on the live tables. Read ../README.md first; this file records only
-- what differs for @@NAME@@.
--
-- @@NAME@@ dedupes against @@NAME@@ only. A company already worked under another
-- vertical is `is_new = true` here and gets enriched again -- they are different
-- audiences. 03_verify.sql asserts that rather than leaving it to be discovered.
--
-- IDENTITY -- same normalizers as every other vertical, same guarantees:
--   companies : normalized domain          (domain_key)
--   people    : normalized LinkedIn slug   (linkedin_key)
--
-- Generated by blocklist_ledger/new_vertical.py.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- @@NAME@@ companies ledger -- identity is domain_key
--
-- Constraint names are prefixed too: a UNIQUE constraint creates an index, and
-- index names share the schema-wide relation namespace, so an unprefixed name
-- here would collide with the other verticals'.
-- ---------------------------------------------------------------------------
create table if not exists public.@@SLUG@@_company_ledger (
  domain_key        text        not null,
  "Name"            text,
  "Company Domain"  text,
  first_seen        timestamptz not null default now(),

  constraint @@SLUG@@_company_ledger_key_uniq  unique (domain_key),
  constraint @@SLUG@@_company_ledger_key_clean check (
    domain_key = lower(btrim(domain_key))
    and length(domain_key) > 0
    and domain_key not like '%/%'      -- no scheme, no path
    and domain_key not like 'www.%'
  ),

  -- THE SENTINEL GUARD. Standard for every vertical created after Highways.
  --
  --   A resolved-domain column is typically a coalesce of a scraped Website and
  --   an AI fallback, and such fallbacks return a literal sentinel ('UNKNOWN',
  --   'N/A', 'none') when they cannot resolve one. normalize_domain('UNKNOWN')
  --   returns 'unknown' -- lowercase, non-empty, no slash, no 'www.' -- so it
  --   satisfies every constraint above and inserts cleanly.
  --
  --   Left unguarded, the first such row claims the key 'unknown' and EVERY
  --   later unresolved company comes back is_new=false: silently blocklisted as
  --   already-worked when nothing was worked at all. A wrong-answer bug, not a
  --   wasted-credit one. Measured on Highways 2026-08-13: 13 such rows in one
  --   table alone, a few hundred across 67.
  --
  --   The test is structural rather than a word blocklist: every real domain
  --   contains a dot, no sentinel does. Paired with the RPC's own pre-check in
  --   02_functions.sql, an unkeyable value is both un-inserted AND unstorable.
  constraint @@SLUG@@_company_ledger_key_shaped check (
    position('.' in domain_key) > 0
  )
);

comment on table public.@@SLUG@@_company_ledger is
  'Seen-before ledger for @@NAME@@ companies. Identity is domain_key (normalized domain). "Name"/"Company Domain" store the values as first seen. Write via ledger_check_@@SLUG@@_company(). Separate from the other verticals'' ledgers on purpose -- they dedupe independently.';
comment on column public.@@SLUG@@_company_ledger.domain_key is
  'Normalized domain -- the unique identity. Produced by normalize_domain(). Must contain a dot: see @@SLUG@@_company_ledger_key_shaped.';
comment on column public.@@SLUG@@_company_ledger."Company Domain" is
  'Domain exactly as first received. Later calls in other formats match on domain_key and do NOT overwrite this.';


-- ---------------------------------------------------------------------------
-- @@NAME@@ people ledger -- identity is linkedin_key (the /in/ vanity slug)
--
-- Created alongside the companies ledger even if no people tables exist yet, so
-- the pair stays symmetrical and the People pass has somewhere to write when it
-- lands. A slug is not a domain, so it gets no dot check --
-- normalize_linkedin() returning null for non-/in/ URLs is the equivalent
-- protection.
-- ---------------------------------------------------------------------------
create table if not exists public.@@SLUG@@_people_ledger (
  linkedin_key        text        not null,
  "Full Name"         text,
  "Linkedin Profile"  text,
  first_seen          timestamptz not null default now(),

  constraint @@SLUG@@_people_ledger_key_uniq  unique (linkedin_key),
  constraint @@SLUG@@_people_ledger_key_clean check (
    linkedin_key = lower(btrim(linkedin_key))
    and length(linkedin_key) > 0
    and linkedin_key not like '%/%'
  )
);

comment on table public.@@SLUG@@_people_ledger is
  'Seen-before ledger for @@NAME@@ people. Identity is linkedin_key (the /in/ slug). Write via ledger_check_@@SLUG@@_person().';
comment on column public.@@SLUG@@_people_ledger.linkedin_key is
  'Normalized LinkedIn vanity slug -- the unique identity. Produced by normalize_linkedin().';


-- ---------------------------------------------------------------------------
-- LOCKDOWN
--
-- Doubles as the integrity guarantee. RLS is enabled with NO policies and table
-- privileges are revoked, so `anon` cannot write these tables directly -- only
-- EXECUTE the SECURITY DEFINER functions. There is therefore NO path by which an
-- unnormalized or unshaped row can be inserted using the publishable key, even
-- deliberately.
-- ---------------------------------------------------------------------------
alter table public.@@SLUG@@_company_ledger enable row level security;
alter table public.@@SLUG@@_people_ledger  enable row level security;

revoke all on table public.@@SLUG@@_company_ledger from anon, authenticated;
revoke all on table public.@@SLUG@@_people_ledger  from anon, authenticated;
""".lstrip()


FUNCTIONS_SQL = r"""
-- ============================================================================
-- @@NAME@@ blocklist ledger
-- @@SLUG@@/02_functions.sql  --  the single-call check-and-insert RPCs
--
-- Run SECOND, after @@SLUG@@/01_schema.sql. Idempotent: safe to re-run.
--
-- DEPENDS ON THE LABS FILES. normalize_domain() and normalize_linkedin() are
-- NOT redefined here -- they are reused from ../02_functions.sql, which must
-- already be applied in this project. One definition means the verticals can
-- never drift into normalizing the same domain differently. The guard below
-- fails loudly rather than letting a missing normalizer surface as a
-- mysterious NULL key.
--
-- ARGUMENT NAMES ARE DELIBERATELY IDENTICAL to every other vertical's RPCs.
-- PostgREST maps JSON body keys to argument names, so keeping them identical
-- means the @@NAME@@ caller differs from its Labs twin by the URL alone --
-- same headers, same body shape, same response mapping. Do not "improve" these.
--
-- THE LOOKUP AND THE INSERT ARE THE SAME STATEMENT.
--   `INSERT ... ON CONFLICT DO NOTHING` against the unique index on the
--   normalized key IS the lookup:
--       key already present -> conflict -> DO NOTHING -> is_new=false
--       key absent          -> row inserted           -> is_new=true
--   Atomic under concurrency, one HTTP call, one billable action.
--
-- Generated by blocklist_ledger/new_vertical.py.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- Precondition guard -- the shared normalizers must exist.
-- ---------------------------------------------------------------------------
do $$
begin
  if to_regprocedure('public.normalize_domain(text)') is null
     or to_regprocedure('public.normalize_linkedin(text)') is null then
    raise exception
      'normalize_domain/normalize_linkedin are missing. Apply blocklist_ledger/02_functions.sql (the Labs file) in this project first -- the @@NAME@@ RPCs reuse them.';
  end if;
end $$;


-- ---------------------------------------------------------------------------
-- Drop earlier signatures. A signature change cannot be handled by CREATE OR
-- REPLACE, and leaving both versions would make PostgREST ambiguous.
-- ---------------------------------------------------------------------------
drop function if exists public.ledger_check_@@SLUG@@_company(text, text);
drop function if exists public.ledger_check_@@SLUG@@_person(text, text);


-- ---------------------------------------------------------------------------
-- ledger_check_@@SLUG@@_company("Company Domain", "Name") -> json
--
-- Returns: { is_new, skipped, key }
--   is_new=true   first @@NAME@@ sighting of this domain -- this call recorded
--                 it. Enrich.
--   is_new=false  domain already in the @@NAME@@ ledger. Skip enrichment.
--   skipped=true  no usable domain in the input; NOTHING was written.
--
-- "Name" is stored as payload and plays no part in matching, so 'Acme Inc',
-- 'Acme, Inc.' and 'ACME' on the same domain are ONE record.
--
-- On a repeat call the stored "Name"/"Company Domain" are left untouched: they
-- record the FIRST sighting, not the latest.
--
-- Idempotent, so rerunning errored cells is safe -- but a rerun of a row that
-- already succeeded returns is_new=false. Treat is_new=true as WRITE-ONCE on
-- the caller's side: letting a rerun clobber a stored true wrongly drops the
-- row from enrichment.
--
-- Reads and writes public.@@SLUG@@_company_ledger ONLY. It cannot see any other
-- vertical's ledger, so a domain worked elsewhere is still new here.
--
-- The dot pre-check mirrors the CHECK constraint in 01_schema.sql -- see the
-- long comment there for why a dotless key is a wrong-answer bug.
-- ---------------------------------------------------------------------------
create or replace function public.ledger_check_@@SLUG@@_company(
  "Company Domain" text default null,
  "Name"           text default null
)
returns json
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_key    text := public.normalize_domain("Company Domain");
  v_is_new boolean;
begin
  -- Unkeyable: empty after normalization, or a sentinel with no dot.
  if v_key is null or position('.' in v_key) = 0 then
    return json_build_object('is_new', false, 'skipped', true, 'key', null);
  end if;

  with ins as (
    insert into public.@@SLUG@@_company_ledger (domain_key, "Name", "Company Domain")
    values (v_key, nullif(btrim(coalesce("Name",'')), ''), nullif(btrim(coalesce("Company Domain",'')), ''))
    on conflict (domain_key) do nothing
    returning 1
  )
  select exists (select 1 from ins) into v_is_new;

  return json_build_object('is_new', v_is_new, 'skipped', false, 'key', v_key);
end;
$$;


-- ---------------------------------------------------------------------------
-- ledger_check_@@SLUG@@_person("Linkedin Profile", "Full Name") -> json
-- Same contract; identity is the LinkedIn slug, "Full Name" is payload.
--
-- skipped=true here means no /in/ slug could be extracted -- a blank cell, a
-- company page, or a malformed URL. Watch this count: those people are NOT
-- being blocklisted, and will be offered again next time.
-- ---------------------------------------------------------------------------
create or replace function public.ledger_check_@@SLUG@@_person(
  "Linkedin Profile" text default null,
  "Full Name"        text default null
)
returns json
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_key    text := public.normalize_linkedin("Linkedin Profile");
  v_is_new boolean;
begin
  if v_key is null then
    return json_build_object('is_new', false, 'skipped', true, 'key', null);
  end if;

  with ins as (
    insert into public.@@SLUG@@_people_ledger (linkedin_key, "Full Name", "Linkedin Profile")
    values (v_key, nullif(btrim(coalesce("Full Name",'')), ''), nullif(btrim(coalesce("Linkedin Profile",'')), ''))
    on conflict (linkedin_key) do nothing
    returning 1
  )
  select exists (select 1 from ins) into v_is_new;

  return json_build_object('is_new', v_is_new, 'skipped', false, 'key', v_key);
end;
$$;


-- ---------------------------------------------------------------------------
-- GRANTS
--
-- anon may EXECUTE these two functions and nothing else.
--
-- NOTE: `revoke ... from public` alone is NOT sufficient on Supabase -- its
-- default privileges grant EXECUTE directly to anon/authenticated, and revoking
-- from PUBLIC does not remove a direct role grant. Both revokes are required.
-- (Caught in Labs testing, not in review -- see ../README.md.)
-- ---------------------------------------------------------------------------
revoke all on function public.ledger_check_@@SLUG@@_company(text, text) from public, anon, authenticated;
revoke all on function public.ledger_check_@@SLUG@@_person(text, text)  from public, anon, authenticated;

grant execute on function public.ledger_check_@@SLUG@@_company(text, text) to anon, authenticated;
grant execute on function public.ledger_check_@@SLUG@@_person(text, text)  to anon, authenticated;
""".lstrip()


VERIFY_SQL = r"""
-- ============================================================================
-- @@NAME@@ blocklist ledger
-- @@SLUG@@/03_verify.sql  --  self-asserting verification suite
--
-- Run THIRD, after @@SLUG@@/01_schema.sql and @@SLUG@@/02_functions.sql.
-- Prints `ALL @@UPPER@@ CHECKS PASSED` or aborts on the first bad assumption.
--
-- Everything it writes it removes: the suite works on sentinel domains under
-- verify-*.example, and the final block deletes exactly those rows and asserts
-- the tables are back to their pre-run counts. Safe to run against a live
-- ledger, and safe to re-run.
--
-- Generated by blocklist_ledger/new_vertical.py.
-- ============================================================================

do $$
declare
  r          json;
  n_before   bigint;
  n_after    bigint;
  p_before   bigint;
  v_tbl      text;
begin
  select count(*) into n_before from public.@@SLUG@@_company_ledger;
  select count(*) into p_before from public.@@SLUG@@_people_ledger;

  -- -------------------------------------------------------------------------
  -- 1. The objects exist with the exact signatures PostgREST will look for.
  --    A wrong signature is the PGRST202 "no such function" class of failure,
  --    which from the caller looks like a 404 with no explanation.
  -- -------------------------------------------------------------------------
  if to_regprocedure('public.ledger_check_@@SLUG@@_company(text, text)') is null then
    raise exception 'CHECK 1 FAILED: ledger_check_@@SLUG@@_company(text,text) missing';
  end if;
  if to_regprocedure('public.ledger_check_@@SLUG@@_person(text, text)') is null then
    raise exception 'CHECK 1 FAILED: ledger_check_@@SLUG@@_person(text,text) missing';
  end if;
  raise notice 'check 1 ok  -- both RPCs exist with the expected signatures';

  -- -------------------------------------------------------------------------
  -- 2. First sighting inserts and reports is_new=true.
  -- -------------------------------------------------------------------------
  r := public.ledger_check_@@SLUG@@_company('https://www.verify-one.example/path?q=1', 'Verify One Ltd');
  if (r->>'is_new')::boolean is not true or (r->>'skipped')::boolean is not false then
    raise exception 'CHECK 2 FAILED: expected is_new=true skipped=false, got %', r;
  end if;
  if r->>'key' <> 'verify-one.example' then
    raise exception 'CHECK 2 FAILED: expected key=verify-one.example, got %', r->>'key';
  end if;
  raise notice 'check 2 ok  -- first sighting inserts, scheme/www/path stripped';

  -- -------------------------------------------------------------------------
  -- 3. Second sighting in a DIFFERENT format is the same record.
  --    This is the whole point of normalizing in the database.
  -- -------------------------------------------------------------------------
  r := public.ledger_check_@@SLUG@@_company('WWW.Verify-One.Example', 'Verify One Limited');
  if (r->>'is_new')::boolean is not false then
    raise exception 'CHECK 3 FAILED: reformatted domain should be is_new=false, got %', r;
  end if;
  raise notice 'check 3 ok  -- casing/www variants collapse to one record';

  -- -------------------------------------------------------------------------
  -- 4. First-sighting payload is preserved, not overwritten by the repeat.
  -- -------------------------------------------------------------------------
  if (select "Name" from public.@@SLUG@@_company_ledger
      where domain_key = 'verify-one.example') <> 'Verify One Ltd' then
    raise exception 'CHECK 4 FAILED: repeat call overwrote the stored "Name"';
  end if;
  raise notice 'check 4 ok  -- payload records the FIRST sighting';

  -- -------------------------------------------------------------------------
  -- 5. Unkeyable input writes nothing.
  -- -------------------------------------------------------------------------
  r := public.ledger_check_@@SLUG@@_company(null, 'No Domain At All');
  if (r->>'skipped')::boolean is not true or (r->>'is_new')::boolean is not false then
    raise exception 'CHECK 5 FAILED: null domain should skip, got %', r;
  end if;
  r := public.ledger_check_@@SLUG@@_company('   ', 'Blank Domain');
  if (r->>'skipped')::boolean is not true then
    raise exception 'CHECK 5 FAILED: blank domain should skip, got %', r;
  end if;
  raise notice 'check 5 ok  -- null/blank domains are skipped, nothing written';

  -- -------------------------------------------------------------------------
  -- 6. THE SENTINEL GUARD.
  --
  --    'UNKNOWN' is what a domain-resolving AI fallback returns when it cannot
  --    verify a domain, and normalize_domain() turns it into the well-formed
  --    key 'unknown'. Unguarded, the first such row would claim that key and
  --    every later unresolved company would be reported already-seen.
  --
  --    Both calls below must skip, and NEITHER may leave a row behind.
  -- -------------------------------------------------------------------------
  r := public.ledger_check_@@SLUG@@_company('UNKNOWN', 'Unresolved Co');
  if (r->>'skipped')::boolean is not true or (r->>'is_new')::boolean is not false then
    raise exception 'CHECK 6 FAILED: UNKNOWN must be skipped, got %', r;
  end if;
  r := public.ledger_check_@@SLUG@@_company('unknown', 'Unresolved Co 2');
  if (r->>'skipped')::boolean is not true then
    raise exception 'CHECK 6 FAILED: lowercase unknown must be skipped, got %', r;
  end if;
  if exists (select 1 from public.@@SLUG@@_company_ledger where domain_key = 'unknown') then
    raise exception 'CHECK 6 FAILED: a row keyed ''unknown'' exists -- the guard leaked';
  end if;
  raise notice 'check 6 ok  -- UNKNOWN and friends are unkeyable, no ''unknown'' row';

  -- -------------------------------------------------------------------------
  -- 7. The CHECK constraint independently refuses a dotless key, so even a
  --    direct insert (not via the RPC) cannot create the collapse of check 6.
  -- -------------------------------------------------------------------------
  begin
    insert into public.@@SLUG@@_company_ledger (domain_key) values ('unknown');
    raise exception 'CHECK 7 FAILED: a dotless domain_key was accepted by the table';
  exception
    when check_violation then
      raise notice 'check 7 ok  -- the table itself refuses a dotless key';
  end;

  -- -------------------------------------------------------------------------
  -- 8. The CHECK constraint refuses an unnormalized key (scheme/case/www).
  -- -------------------------------------------------------------------------
  begin
    insert into public.@@SLUG@@_company_ledger (domain_key) values ('WWW.Bad.Example');
    raise exception 'CHECK 8 FAILED: an unnormalized domain_key was accepted';
  exception
    when check_violation then
      raise notice 'check 8 ok  -- the table refuses an unnormalized key';
  end;

  -- -------------------------------------------------------------------------
  -- 9. VERTICAL ISOLATION -- the headline behavioural claim.
  --    A domain already in ANY other vertical's ledger must still be new here.
  --
  --    Discovered dynamically rather than naming siblings, so this check keeps
  --    asserting the full claim as verticals are added. Naming them explicitly
  --    is how the assertion quietly narrows to "isolated from Labs" once there
  --    are six of them.
  -- -------------------------------------------------------------------------
  for v_tbl in
    select c.relname
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'
       and c.relkind = 'r'
       and (c.relname = 'company_ledger' or c.relname like '%\_company\_ledger')
       and c.relname <> '@@SLUG@@_company_ledger'
  loop
    execute format(
      'insert into public.%I (domain_key, "Name") values ($1, $2) '
      'on conflict (domain_key) do nothing', v_tbl)
      using 'verify-shared.example', 'Planted By @@NAME@@ Verify';
  end loop;

  r := public.ledger_check_@@SLUG@@_company('verify-shared.example', 'Shared Domain Co');
  if (r->>'is_new')::boolean is not true then
    raise exception
      'CHECK 9 FAILED: a domain present in every other vertical''s ledger must still be new to @@NAME@@, got %', r;
  end if;
  raise notice 'check 9 ok  -- @@NAME@@ dedupes against @@NAME@@ only';

  -- -------------------------------------------------------------------------
  -- 10. People RPC: insert, repeat, and slug normalization.
  -- -------------------------------------------------------------------------
  r := public.ledger_check_@@SLUG@@_person('https://www.linkedin.com/in/Verify-Person/', 'Verify Person');
  if (r->>'is_new')::boolean is not true then
    raise exception 'CHECK 10 FAILED: first person sighting should be is_new=true, got %', r;
  end if;
  r := public.ledger_check_@@SLUG@@_person('linkedin.com/in/verify-person', 'Verify Person Again');
  if (r->>'is_new')::boolean is not false then
    raise exception 'CHECK 10 FAILED: same slug in another format should be is_new=false, got %', r;
  end if;
  r := public.ledger_check_@@SLUG@@_person('https://www.linkedin.com/company/acme', 'Not A Person');
  if (r->>'skipped')::boolean is not true then
    raise exception 'CHECK 10 FAILED: a company URL should skip, got %', r;
  end if;
  raise notice 'check 10 ok -- people RPC inserts, dedupes and rejects non-/in/ URLs';

  -- -------------------------------------------------------------------------
  -- 11. anon can EXECUTE the RPCs but cannot read or write the tables.
  --     This is the security model AND the integrity model in one.
  -- -------------------------------------------------------------------------
  if not has_function_privilege('anon',
        'public.ledger_check_@@SLUG@@_company(text, text)', 'execute') then
    raise exception 'CHECK 11 FAILED: anon cannot execute the company RPC';
  end if;
  if has_table_privilege('anon', 'public.@@SLUG@@_company_ledger', 'select')
     or has_table_privilege('anon', 'public.@@SLUG@@_company_ledger', 'insert') then
    raise exception 'CHECK 11 FAILED: anon has direct table access -- lockdown is broken';
  end if;
  if not (select relrowsecurity from pg_class
          where oid = 'public.@@SLUG@@_company_ledger'::regclass) then
    raise exception 'CHECK 11 FAILED: RLS is not enabled on @@SLUG@@_company_ledger';
  end if;
  raise notice 'check 11 ok -- anon may execute the RPCs and nothing else; RLS on';

  -- -------------------------------------------------------------------------
  -- 12. No unresolved column references were ever stored. A typed "/Name"
  --     instead of a picked one produced ten junk rows during the Labs setup.
  -- -------------------------------------------------------------------------
  if exists (select 1 from public.@@SLUG@@_company_ledger
             where domain_key like '/%' or "Name" like '/%' or "Company Domain" like '/%') then
    raise exception
      'CHECK 12 FAILED: a value starting with "/" is stored -- a column reference was sent literally, not resolved';
  end if;
  raise notice 'check 12 ok -- no unresolved column references stored';

  -- -------------------------------------------------------------------------
  -- CLEANUP -- remove exactly what this suite created, then prove it.
  -- -------------------------------------------------------------------------
  delete from public.@@SLUG@@_company_ledger
   where domain_key in ('verify-one.example', 'verify-shared.example');
  delete from public.@@SLUG@@_people_ledger where linkedin_key = 'verify-person';

  -- Same discovery as check 9, so every planted row is removed. The "Name"
  -- predicate means a real 'verify-shared.example' row someone else owns is
  -- left alone.
  for v_tbl in
    select c.relname
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'
       and c.relkind = 'r'
       and (c.relname = 'company_ledger' or c.relname like '%\_company\_ledger')
       and c.relname <> '@@SLUG@@_company_ledger'
  loop
    execute format(
      'delete from public.%I where domain_key = $1 and "Name" = $2', v_tbl)
      using 'verify-shared.example', 'Planted By @@NAME@@ Verify';
  end loop;

  select count(*) into n_after from public.@@SLUG@@_company_ledger;
  if n_after <> n_before then
    raise exception
      'CLEANUP FAILED: company ledger has % rows, started with % -- verify rows left behind',
      n_after, n_before;
  end if;
  select count(*) into n_after from public.@@SLUG@@_people_ledger;
  if n_after <> p_before then
    raise exception
      'CLEANUP FAILED: people ledger has % rows, started with %', n_after, p_before;
  end if;

  raise notice '----------------------------------------';
  raise notice 'ALL @@UPPER@@ CHECKS PASSED';
  raise notice 'company ledger rows: %   people ledger rows: %', n_before, p_before;
  raise notice '----------------------------------------';
end $$;
""".lstrip()


